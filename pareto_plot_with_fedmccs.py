# -*- coding: utf-8 -*-
"""
pareto_plot_with_fedmccs.py - Pareto frontier plot (Accuracy vs Energy)
combining the metaheuristic comparison (method x fitness_mode) with the
FedMCCS baseline, using the CORRECTED energy-per-client metric for FedMCCS.

Why a corrected metric is needed (see fedmccs_experiment.py for the full
derivation): FedMCCS's resource-budget gate caps how many clients can ever
clear its admission thresholds in a round, independent of the requested
participation rate. So at higher rates its `fulfillment_rate` drops below
1, and dividing total energy by the TARGET client count (as the base
Energy_Per_Selected_Client column does) makes FedMCCS look like it gets
cheaper per client purely because a roughly-fixed energy total is divided
by a growing, mostly-unmet target -- not because it's actually training
more clients. This module uses Energy_Per_Actual_Selected_Client instead
(falls back to the base column for the metaheuristic rows, where
fulfillment is always 1 and the two are equivalent).

Usage:
    from pareto_plot_with_fedmccs import plot_pareto_with_fedmccs
    plot_pareto_with_fedmccs(
        comparison_csv='participation_rate_comparison.csv',
        fedmccs_csv='fedmccs_baseline_results.csv',
        output_path='pareto_frontier_with_fedmccs.png',
    )
"""

import pandas as pd
import matplotlib.pyplot as plt


METHOD_MARKERS = {
    'ACO': 'o', 'RSELECT': 's', 'PSO': '^', 'GA': 'D',
    'GWO': 'v', 'DE': '<', 'SA': '>', 'TSA': 'p',
}
FITNESS_COLORS = {
    'resource': '#2ca02c',      # green
    'learning': '#1f77b4',      # blue
    'exploration': '#d62728',   # red
}
FITNESS_LABELS = {
    'resource': 'RESOURCE', 'learning': 'LEARNING', 'exploration': 'EXPLORATION',
}


def _prep_fedmccs(df_fedmccs):
    """
    Return (x, y, rate_labels) for FedMCCS using the corrected energy
    metric. Falls back to computing it on the fly (target * fulfillment)
    if Energy_Per_Actual_Selected_Client isn't present yet -- e.g. when
    plotting an older CSV generated before fedmccs_experiment.py was
    updated to emit that column directly.
    """
    df = df_fedmccs.copy()

    if 'Energy_Per_Actual_Selected_Client' not in df.columns:
        n_actual = df['N_Selected_Clients'] * df['Fulfillment_Rate_Avg']
        df['Energy_Per_Actual_Selected_Client'] = df['Energy_Avg'] / n_actual
        if 'N_Selected_Clients_Actual' not in df.columns:
            df['N_Selected_Clients_Actual'] = n_actual

    x = df['Energy_Per_Actual_Selected_Client']
    y = df['Accuracy_Avg']
    n_actual = df['N_Selected_Clients_Actual']
    rate_labels = [
        f"{int(r * 100)}%\n(n\u2248{n:.1f})"
        for r, n in zip(df['Participation_Rate'], n_actual)
    ]
    return x, y, rate_labels


def plot_pareto_with_fedmccs(comparison_csv, fedmccs_csv, output_path,
                              figsize=(13, 9), dpi=150, annotate_rates=True):
    """
    Build and save the combined Pareto frontier: metaheuristics (marker =
    Selection_Method, color = Fitness_Mode) plus FedMCCS (gold stars,
    corrected energy metric).

    Args:
        comparison_csv: path to participation_rate_comparison.csv
            (metaheuristic results; must have Selection_Method,
            Fitness_Mode, Energy_Per_Selected_Client, Accuracy_Avg,
            Participation_Rate columns).
        fedmccs_csv: path to fedmccs_baseline_results.csv (must have
            Participation_Rate, Accuracy_Avg, Energy_Avg,
            N_Selected_Clients, Fulfillment_Rate_Avg -- and ideally
            Energy_Per_Actual_Selected_Client / N_Selected_Clients_Actual
            if generated by the updated fedmccs_experiment.py).
        output_path: where to save the PNG.
        figsize, dpi: matplotlib figure sizing.
        annotate_rates: if True, label each point with its participation
            rate (and, for FedMCCS, the actual selected-client count).

    Returns:
        (fig, ax): the matplotlib figure/axes, in case the caller wants
        further customization before saving/showing.
    """
    df_meta = pd.read_csv(comparison_csv)
    df_fedmccs = pd.read_csv(fedmccs_csv)

    fig, ax = plt.subplots(figsize=figsize)

    # --- Metaheuristics: marker = method, color = fitness mode ---
    for _, row in df_meta.iterrows():
        method = row['Selection_Method']
        fmode = row['Fitness_Mode']
        marker = METHOD_MARKERS.get(method, 'X')
        color = FITNESS_COLORS.get(fmode, 'gray')
        x = row['Energy_Per_Selected_Client']
        y = row['Accuracy_Avg']
        ax.scatter(x, y, marker=marker, color=color, s=110,
                   edgecolors='black', linewidths=0.6, alpha=0.85, zorder=3)
        if annotate_rates:
            ax.annotate(f"{int(row['Participation_Rate'] * 100)}%", (x, y),
                       fontsize=7, xytext=(4, 4), textcoords='offset points')

    # --- FedMCCS: gold stars, corrected energy metric ---
    x_fed, y_fed, labels_fed = _prep_fedmccs(df_fedmccs)
    ax.scatter(x_fed, y_fed, marker='*', color='gold', s=380,
               edgecolors='black', linewidths=1.0, zorder=5)
    if annotate_rates:
        for x, y, label in zip(x_fed, y_fed, labels_fed):
            ax.annotate(label, (x, y), fontsize=7.5, xytext=(6, 6),
                       textcoords='offset points')

    # --- Legends: method (shape), fitness mode (color), FedMCCS ---
    method_handles = [
        plt.Line2D([0], [0], marker=METHOD_MARKERS[m], color='w', markerfacecolor='gray',
                  markeredgecolor='black', markersize=10, label=m)
        for m in df_meta['Selection_Method'].unique() if m in METHOD_MARKERS
    ]
    fitness_handles = [
        plt.Line2D([0], [0], marker='o', color='w', markerfacecolor=FITNESS_COLORS[f],
                  markeredgecolor='black', markersize=10, label=FITNESS_LABELS[f])
        for f in df_meta['Fitness_Mode'].unique() if f in FITNESS_COLORS
    ]
    fedmccs_handle = [
        plt.Line2D([0], [0], marker='*', color='w', markerfacecolor='gold',
                  markeredgecolor='black', markersize=16, label='FedMCCS')
    ]
    ax.legend(handles=method_handles + fitness_handles + fedmccs_handle,
             loc='center left', bbox_to_anchor=(1.01, 0.5), fontsize=10, frameon=True)

    ax.set_xlabel('Energy per Selected Client (Wh) -- Lower = Better', fontsize=12)
    ax.set_ylabel('Accuracy -- Higher = Better', fontsize=12)
    ax.set_title(
        'Pareto Frontier: Accuracy vs Energy Consumption\n'
        '(Metaheuristics by Method & Fitness Mode, vs FedMCCS)',
        fontsize=14, fontweight='bold',
    )
    ax.grid(True, alpha=0.3)

    fig.tight_layout()
    fig.savefig(output_path, dpi=dpi, bbox_inches='tight')

    return fig, ax


if __name__ == "__main__":
    import argparse

    parser = argparse.ArgumentParser(description="Generate Pareto frontier plot with FedMCCS")
    parser.add_argument('--comparison_csv', default='participation_rate_comparison.csv')
    parser.add_argument('--fedmccs_csv', default='fedmccs_baseline_results.csv')
    parser.add_argument('--output', default='pareto_frontier_with_fedmccs.png')
    args = parser.parse_args()

    plot_pareto_with_fedmccs(args.comparison_csv, args.fedmccs_csv, args.output)
    print(f"Saved: {args.output}")
